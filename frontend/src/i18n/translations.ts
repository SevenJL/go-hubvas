export function translate(language: Language, source: string, params?: TranslationParams) {
  let result = language === 'zh' ? (zh[source] ?? source) : source;
  if (params) {
    for (const [key, value] of Object.entries(params)) {
      result = result.replaceAll(`{${key}}`, String(value));
    }
  }
  return result;
}
